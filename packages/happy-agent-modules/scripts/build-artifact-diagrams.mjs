#!/usr/bin/env node
// Bundles the renderer the standard `<happy-diagram>` element loads, Beautiful Mermaid with its
// elkjs layout, into one browser script, and writes it as the module the daemon serves at
// `/api/v1/diagrams.js`. The output is committed: the daemon and its single binary serve it as a
// string, so neither needs the renderer installed.
//
// Usage: node scripts/build-artifact-diagrams.mjs <beautiful-mermaid package directory>
// esbuild must be importable from here, or named by the ESBUILD environment variable.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(packageRoot, "sources", "artifactData", "impl", "artifactDiagramsScript.ts");

async function main() {
    const source = process.argv[2];
    if (source === undefined) throw new Error("Name the beautiful-mermaid package directory.");
    const mermaidRoot = resolve(source);
    const manifest = JSON.parse(readFileSync(join(mermaidRoot, "package.json"), "utf8"));
    if (manifest.name !== "beautiful-mermaid")
        throw new Error(`${mermaidRoot} is not beautiful-mermaid.`);
    const { build } = await import(process.env.ESBUILD ?? "esbuild");
    const result = await build({
        stdin: {
            contents: [
                `import { renderMermaidSVG } from ${JSON.stringify(join(mermaidRoot, "dist", "index.js"))};`,
                "globalThis.happyDiagrams = { render: renderMermaidSVG };",
            ].join("\n"),
            resolveDir: mermaidRoot,
            loader: "js",
        },
        banner: {
            js: `/* Happy diagram renderer, served by Happy Agent. Beautiful Mermaid ${manifest.version} (MIT, Copyright (c) 2026 Craft Docs), elkjs (EPL-2.0, https://github.com/kieler/elkjs), entities (BSD-2-Clause, Copyright (c) Felix Boehm). See THIRD-PARTY-NOTICES.md of Happy Agent. */`,
        },
        bundle: true,
        format: "iife",
        legalComments: "inline",
        minify: true,
        platform: "browser",
        target: "es2020",
        write: false,
    });
    const script = result.outputFiles[0].text;
    const module = [
        `// Generated by scripts/build-artifact-diagrams.mjs from beautiful-mermaid ${manifest.version}. Do not edit.`,
        "// Beautiful Mermaid is MIT-licensed (Craft Docs), elkjs EPL-2.0 (Kiel University and others),",
        "// and entities BSD-2-Clause (Felix Boehm); their notices are kept inside the script.",
        "",
        "/** The diagram renderer `<happy-diagram>` loads from `/api/v1/diagrams.js`. */",
        `export const ARTIFACT_DIAGRAMS_SCRIPT: string = ${JSON.stringify(script)};`,
        "",
    ].join("\n");
    writeFileSync(output, module);
    console.log(`Wrote ${output} (${Math.round(script.length / 1024)} KiB of script).`);
}

await main();
